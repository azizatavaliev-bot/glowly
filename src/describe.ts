/** Польза товара: назначение + состав + тип средства. Всегда 2–5 пунктов. */
export function benefits(p: Product): string[] {
  const n = `${p.full} ${p.spec ?? ''}`
  const out: string[] = []

  for (const [re, text] of PURPOSE) {
    if (re.test(n) && !out.includes(text)) out.push(text)
    if (out.length === 3) break
  }
  for (const t of tags(p)) {
    if (out.length >= 4) break
    out.push(`${t.label} — ${t.text.charAt(0).toLowerCase()}${t.text.slice(1)}`)
  }
  // тип средства добавляем всегда — он объясняет, как товар вообще работает
  for (const [re, text] of BY_TYPE) {
    if (out.length >= 4) break
    if (re.test(n) && !out.includes(text)) { out.push(text); break }
  }
  // добиваем до двух пунктов через категорию — пустых карточек быть не должно
  const byCat: Record<string, string> = {
    'Наборы': 'Несколько средств одной линии сразу — удобно пробовать бренд и дарить',
    'Макияж': 'Тон и текстуры корейского макияжа: лёгкое покрытие, естественный финиш',
    'Губы': 'Уход и цвет в одном — губы не сохнут',
    'Очищение': 'Чистая кожа — база, без которой остальной уход не работает',
    'Маски и патчи': 'Быстрый результат за 15–20 минут',
    'Уход за лицом': 'Ежедневный уход за кожей лица',
    'Солнцезащита': 'Ежедневная защита от солнца — без неё уход теряет смысл',
    'Волосы': 'Уход за волосами и кожей головы',
    'Тело': 'Уход за кожей тела',
    'Гигиена': 'Ежедневная гигиена',
    'Гаджеты': 'Салонные процедуры дома',
    'БАДы': 'Работа над кожей изнутри',
  }
  if (out.length < 2 && byCat[p.cat] && !out.includes(byCat[p.cat])) out.push(byCat[p.cat])
  if (!out.length) out.push(what(p))
  return out.slice(0, 5)
}
