/** Польза: 2–5 пунктов, каждый со своим смайликом. */
export function benefits(p: Product): string[] {
  const out: string[] = []
  for (const pur of purposes(p)) if (!out.includes(pur.benefit)) out.push(pur.benefit)
  for (const t of tags(p)) {
    if (out.length >= 4) break
    const line = `${t.label} — ${t.text.charAt(0).toLowerCase()}${t.text.slice(1)}`
    if (!out.includes(line)) out.push(line)
  }
  // текст про формат уже стоит в описании выше — сюда берём запасной по категории
  if (out.length < 2) {
    const byCat: Record<string, string> = {
      'Наборы': 'Несколько средств линии сразу — удобно пробовать бренд и дарить',
      'Макияж': 'Лёгкие текстуры корейского макияжа с естественным финишем',
      'Губы': 'Цвет и уход одновременно — губы не сохнут',
      'Очищение': 'Чистая кожа — база, без которой остальной уход не работает',
      'Маски и патчи': 'Заметный результат уже после первого применения',
      'Уход за лицом': 'Ежедневный уход за кожей лица',
      'Солнцезащита': 'Ежедневная защита от солнца',
      'Волосы': 'Уход за волосами и кожей головы',
      'Тело': 'Уход за кожей тела',
      'Гигиена': 'Ежедневная гигиена',
      'Гаджеты': 'Салонные процедуры дома',
      'БАДы': 'Работа над кожей изнутри',
    }
    const zone = zoneOf(p)
    const care = /бальзам|маска|эссенция/i.test(split(p).title)
    const line = zone === 'hair' ? byCat['Волосы']
      : zone === 'lips' && care ? 'Смягчает губы и убирает шелушения'
      : byCat[p.cat]
    if (line && !out.includes(line)) out.push(line)
  }
  return out.slice(0, 5).map(line => `${emojiFor(line)} ${line}`)
}

/** Кому подойдёт. */
export function forWhom(p: Product): string[] {
  const pur = purposes(p)
  if (pur.length) return pur.map(x => x.who).slice(0, 3)
  if (p.cat === 'Губы' && /бальзам|маска|эссенция/i.test(split(p).title)) return ['тем, у кого губы сохнут и шелушатся']
  if (p.cat === 'Макияж' || p.cat === 'Губы') return ['для повседневного макияжа']
  if (zoneOf(p) === 'hair') return ['для ежедневного ухода за волосами']
  if (p.cat === 'Наборы') return ['хороший старт, чтобы попробовать бренд']
  if (p.cat === 'Гигиена') return ['для ежедневной чистки зубов']
  if (p.cat === 'Тело') return ['для ежедневного ухода за телом']
  if (p.cat === 'Гаджеты') return ['тем, кто хочет усилить домашний уход']
  return ['подходит всем типам кожи']
}

/** Как применять: шаги по порядку. */
export function steps(p: Product): string[] {
  return typeOf(p).steps
}

/** Короткая строка о типе средства. */
export function what(p: Product): string {
  const t = typeOf(p)
  const v = volume(p)
  return `${t.name.charAt(0).toUpperCase()}${t.name.slice(1)} от ${p.brand}${v.text !== '—' ? `, ${v.text}` : ''}.`
}

/** Деньги: короб и цена за мл. */
export function money(p: Product) {
  const v = volume(p)
  return {
    box: p.packQty ? p.price * p.packQty : null,
    boxQty: p.packQty,
    perMl: v.ml ? p.price / v.ml : null,
  }
}
