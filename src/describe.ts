/* ───────── готовые тексты карточки ───────── */

/** Связное описание в 2–3 предложения. */
export function summary(p: Product): string {
  const t = typeOf(p)
  const v = volume(p)
  const size = v.text !== '—' ? `, ${v.text}` : ''
  // назначение не дублируем: оно идёт ниже в блоке «Чем полезен»
  const first = `${t.name.charAt(0).toUpperCase()}${t.name.slice(1)} от ${p.brand}${size} — ${t.gist}.`
  const second = p.spec ? `Вариант: ${p.spec}.` : ''
  const third = p.exp ? `Срок годности до ${p.exp}.` : ''
  return [first, second, third].filter(Boolean).join(' ')
}

/** Польза: 2–5 пунктов. */
export function benefits(p: Product): string[] {
  const out: string[] = []
  for (const pur of purposes(p)) if (!out.includes(pur.benefit)) out.push(pur.benefit)
  for (const t of tags(p)) {
    if (out.length >= 4) break
    const line = `${t.label} — ${t.text.charAt(0).toLowerCase()}${t.text.slice(1)}`
    if (!out.includes(line)) out.push(line)
  }
  if (out.length < 2) {
    const g = typeOf(p).gist
    const line = g.charAt(0).toUpperCase() + g.slice(1)
    if (!out.includes(line)) out.push(line)
  }
  return out.slice(0, 5)
}

/** Кому подойдёт. */
export function forWhom(p: Product): string[] {
  const pur = purposes(p)
  if (pur.length) return pur.map(x => x.who).slice(0, 3)
  if (p.cat === 'Макияж' || p.cat === 'Губы') return ['для повседневного макияжа']
  if (p.cat === 'Волосы') return ['для ежедневного ухода за волосами']
  if (p.cat === 'Наборы') return ['хороший старт, чтобы попробовать бренд']
  return ['подходит всем типам кожи']
}

/** Как применять: шаги по порядку. */
export function steps(p: Product): string[] {
  return typeOf(p).steps
}

/** Короткая строка о типе средства. */
export function what(p: Product): string {
  const t = typeOf(p)
  const v = volume(p)
  return `${t.name.charAt(0).toUpperCase()}${t.name.slice(1)} от ${p.brand}${v.text !== '—' ? `, ${v.text}` : ''}.`
}

/** Деньги: короб и цена за мл. */
export function money(p: Product) {
  const v = volume(p)
  return {
    box: p.packQty ? p.price * p.packQty : null,
    boxQty: p.packQty,
    perMl: v.ml ? p.price / v.ml : null,
  }
}
