function typeOf(p: Product): TypeInfo {
  const title = split(p).title.toLowerCase()
  for (const [re, info] of TYPES) if (re.test(title)) return info
  return {
    name: 'средство',
    gist: 'уход за кожей',
    steps: ['Наносить на очищенную кожу', 'Схема ухода: очищение → тонер → сыворотка → крем'],
  }
}

/* ───────── назначение ───────── */

type Purpose = { benefit: string; who: string }

/** Слова в названии значат разное для лица и для волос, поэтому у каждой области свой список. */
type Zone = 'face' | 'hair' | 'makeup' | 'lips' | 'body' | 'other'

function zoneOf(p: Product): Zone {
  const title = split(p).title.toLowerCase()
  if (p.cat === 'Волосы' || /расческа|расчёска/.test(title)) return 'hair'
  if (p.cat === 'Губы') return 'lips'
  if (p.cat === 'Макияж') return 'makeup'
  if (p.cat === 'Тело') return 'body'
  if (p.cat === 'Гигиена' || p.cat === 'Гаджеты') return 'other'
  return 'face'
}

