export function tags(p: Product): Tag[] {
  const n = `${p.full} ${p.spec ?? ''}`
  const out: Tag[] = []
  for (const [re, label, text] of RULES) {
    if (re.test(n) && !out.some(t => t.label === label)) out.push({ label, text })
    if (out.length === 5) break
  }
  return out
}

