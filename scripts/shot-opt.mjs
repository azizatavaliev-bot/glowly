// оптовая витрина /opt на телефоне: первый экран, каталог, корзина ниже и выше минимальной суммы
import { chromium } from 'playwright'
const base = (process.argv[2] || 'http://localhost:5280').replace(/\/$/, '')
const b = await chromium.launch()
const m = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await m.goto(base + '/opt', { waitUntil: 'networkidle' })
await m.evaluate(() => localStorage.removeItem('lilo.cart.opt'))
await m.waitForTimeout(3000)
await m.screenshot({ path: '/tmp/opt-1.png' })
await m.evaluate(() => { const g = document.querySelector('.catalog .grid'); scrollTo(0, g.getBoundingClientRect().top + scrollY - 130) })
await m.waitForTimeout(800)
await m.locator('.catalog .card .buy').first().click()
await m.waitForTimeout(2500)
await m.screenshot({ path: '/tmp/opt-2.png' })
await m.locator('.mbar-cart').click(); await m.waitForTimeout(600)
await m.screenshot({ path: '/tmp/opt-3.png' })
console.log('ниже минимума:', await m.locator('.cart .off-btn').innerText(), '| кнопок отправки:', await m.locator('.cart .wa-btn').count())
for (let i = 0; i < 8; i++) await m.locator('.cart .stepper button').nth(1).click()
await m.waitForTimeout(300)
console.log('ступень при 9 шт:', await m.locator('.cart .tier').innerText().catch(() => 'нет'))
for (let i = 0; i < 16; i++) await m.locator('.cart .stepper button').nth(1).click()
await m.waitForTimeout(300)
console.log('ступень при 25 шт:', await m.locator('.cart .tier').innerText().catch(() => 'нет'))
await m.waitForTimeout(400)
await m.screenshot({ path: '/tmp/opt-4.png' })
const href = await m.locator('.cart .wa-btn').getAttribute('href')
console.log(decodeURIComponent(href.split('text=')[1]))
// розница не должна была измениться
await m.goto(base + '/', { waitUntil: 'networkidle' })
console.log('розница, первая цена:', await m.locator('.catalog .card .price').first().innerText().then(t => t.replace(/\s+/g, ' ')), '| корзина розницы:', await m.evaluate(() => localStorage.getItem('lilo.cart')))
console.log('overflow', await m.evaluate(() => document.documentElement.scrollWidth - innerWidth))
await b.close()
